# on the synthetic dataset generated by data/make_dataset.py
# ---------------------------------------------------------------------------
if __name__ == "__main__":
    import csv
    import os

    data_path = os.path.join(
        os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
        "data",
        "synthetic_materials.csv",
    )

    print("=== normalize() demo on hardcoded examples ===\n")
    examples = [
        "HEX BOLT M16 X 50 MM SS304",
        "Hexagonal Bolt M16*50 Stainless Steel 304",
        "SS 304 HEX HEAD BOLT M16 X 50",
        "HEX HEAD BOLT M16 50MM SS304",
    ]
    for e in examples:
        print(f"  RAW:  {e}")
        print(f"  NORM: {normalize(e)}\n")

    if os.path.exists(data_path):
        print("=== normalize() applied to your synthetic dataset ===\n")
        with open(data_path, newline="", encoding="utf-8") as f:
            reader = csv.DictReader(f)
            rows = list(reader)
        for r in rows[:10]:  # just show the first 10 so output isn't huge
            print(f"  [{r['cpse']}] {r['original_description']}")
            print(f"       -> {normalize(r['original_description'])}\n")
        print(f"(showing first 10 of {len(rows)} rows)")
    else:
        print(f"No dataset found at {data_path} — run data/make_dataset.py first.")
